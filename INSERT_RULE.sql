	RULE_ID                	NUMBER IDENTITY(1,1),
	RULE_TYPE_ID          	NUMBER,
	RULE_NAME              	VARCHAR(100) NULL,
	RULE_DESCRIPTION       	VARCHAR(512) NULL,
	RULE_COMMAND           	VARCHAR(1024) NULL,
	RESULT_DATE_TYPE       	VARCHAR(100) NULL,
	RULE_RESOLUTION        	VARCHAR(512) NULL,
