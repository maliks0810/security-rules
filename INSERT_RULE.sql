	IS_DELETED             	NUMBER(38,0) NULL,
	EXCEPTION_TYPE_ID      	NUMBER(38,0) NULL,
	INTRADAY_HARNESS_ID    	NUMBER(38,0) NULL,
	DQM_APP_ID             	NUMBER(38,0) NULL,
